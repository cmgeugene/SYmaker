def seed() -> None:
    if db.query_one("SELECT id FROM guidelines LIMIT 1"):
        return
    for title, category, content in DEFAULT_GUIDELINES:
        gid = db.execute(
            "INSERT INTO guidelines(title, category, content, version, updated_at) VALUES(?,?,?,1,?)",
            (title, category, content, db.now()),
        )
        db.execute(
            "INSERT INTO guideline_versions(guideline_id, version, content, note, created_at) VALUES(?,?,?,?,?)",
            (gid, 1, content, "기본 지침", db.now()),
        )
